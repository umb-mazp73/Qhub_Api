from typing import Protocol

from app.domain.value_objects import AccessToken, OwnerId


class PasswordHasher(Protocol):
    async def hash_password(self, plain: str) -> str: ...
    async def verify_password(self, plain: str, encoded: str) -> bool: ...


class ApiKeyCodec(Protocol):
    def generate(self) -> str: ...
    def digest(self, plain: str) -> str: ...


class AccessTokenService(Protocol):
    def issue(self, owner: OwnerId) -> AccessToken: ...
    def verify(self, token: str) -> OwnerId: ...
