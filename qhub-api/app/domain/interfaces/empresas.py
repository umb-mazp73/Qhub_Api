from datetime import datetime
from typing import Protocol
from uuid import UUID

from app.domain.models import EmpresaChanges, Page
from app.domain.entities import Empresa
from app.domain.value_objects import OwnerId


class EmpresaRepository(Protocol):
    async def create(self, name: str) -> Empresa: ...
    async def list_all(self, page: Page) -> tuple[Empresa, ...]: ...
    async def get(self, empresa_id: UUID) -> Empresa | None: ...
    async def update(self, empresa_id: UUID, changes: EmpresaChanges) -> Empresa: ...
    async def revoke_active_keys(self, owner: OwnerId, at: datetime) -> None: ...
    async def insert_key_digest(self, owner: OwnerId, digest: str) -> None: ...
